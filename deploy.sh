#!/bin/bash
# Deploys this repo to production (webserver -> https://web.abofonsa.com) and verifies the result.
# Run it by hand from a clean checkout of the commit you want live:
#
#   ./deploy.sh                 # build+push images, ship config, restart, verify
#   ./deploy.sh --skip-build    # redeploy an already-pushed TAG (e.g. a rollback)
#   ./deploy.sh --verify-only   # touch nothing, just run the health/HTTP checks
#   TAG=a1b2c3d ./deploy.sh --skip-build   # roll back to a previous image
#   ./deploy.sh --yes           # non-interactive; skips the prompts (NOT the certbot one)
#
#   ./deploy.sh --recover       # stack is running but its compose.yml/.env went missing
#   ./deploy.sh --bootstrap     # FIRST-TIME INSTALL on a server with nothing deployed
#   ./deploy.sh --bootstrap --with-nginx        # ... and install the host nginx site
#   ./deploy.sh --bootstrap --with-nginx --with-tls   # ... and run certbot for the domain
#
# CHANNELS - where the images being deployed come from:
#
#   ./deploy.sh --channel local    # (default) build them here, push to the private registry
#   ./deploy.sh --channel github   # deploy the images GitHub Actions already built, from GHCR
#
#   local   builds both images on this machine with ./build.sh and pushes them to
#           docker.jojoaddison.net. What you deploy is what your working tree produces.
#   github  builds nothing. .github/workflows/release.yml built and pushed the images to
#           ghcr.io/$GHCR_OWNER when the commit landed on main; this deploys exactly those.
#           The tag is the FULL commit SHA, because that is what the workflow tags with.
#
#           TAG=<full-sha> ./deploy.sh --channel github   # deploy/roll back to any built commit
#
# The channel decides two things and nothing else: whether a build runs here, and what REGISTRY
# the server's .env is pointed at. Everything after that - config sync, restart, health, the
# verification suite - is identical, so a deploy cannot behave differently depending on where its
# image was built.
#
# What it does, in order: preflight -> [bootstrap: create dirs/networks/.env, ship config] ->
# build+push (local channel) or confirm the image is pullable (github channel) -> sync compose.yml
# -> point the server's .env at the new REGISTRY+TAG -> pull + recreate -> wait for the API to
# report healthy -> [bootstrap: nginx + TLS] -> verify internally and publicly. Every mutating step
# is announced before it runs, and the irreversible-ish ones prompt unless --yes is passed.
#
# All three secrets this app needs (JWT_SIGNING_KEY, BOOTSTRAP_ADMIN_PASSWORD, ENQUIRY_IP_SALT) are
# generated by `openssl rand` running ON THE SERVER during bootstrap, so they never exist on the
# deploying machine, in its shell history, or on the wire. Unlike the sibling app there is no
# third-party key to supply by hand, so nothing has to be pasted in.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

# --- Configuration -----------------------------------------------------------------------------

SSH_HOST="${SSH_HOST:-webserver}"                                # ~/.ssh/config alias
REMOTE_DIR="${REMOTE_DIR:-~/webroot/01-healthconnect/abofonsa}"  # expanded remotely, not here
PUBLIC_URL="${PUBLIC_URL:-https://web.abofonsa.com}"
FRONTEND_PORT="${FRONTEND_PORT:-8082}"   # loopback-only port the host nginx proxies to
# Must match `container_name:` in infra/prod-server/compose.yml. Hyphens, not underscores: an
# underscore is illegal in a hostname, so a container named hc_abofonsa_api cannot be addressed
# over the compose network without Tomcat rejecting the request with a bare 400.
API_CONTAINER="abofonsa-api"
WEB_CONTAINER="abofonsa-web"
MONGO_CONTAINER="abofonsa-mongodb"
APP_NETWORK="abofonsanet"
NGINX_CONF="abofonsa.conf"

# The OTel javaagent baked into the API image costs real boot time on this single-core host.
# This is expected, not a hang - see infra/prod-server/compose.yml's healthcheck comment.
HEALTH_TIMEOUT_SECS="${HEALTH_TIMEOUT_SECS:-720}"
HEALTH_POLL_SECS=10

# Image source. REGISTRY is normally derived from the channel below, but an explicit REGISTRY in
# the environment still wins for either channel - captured here, before the channel overwrites it.
LOCAL_REGISTRY="docker.jojoaddison.net"
GHCR_OWNER="${GHCR_OWNER:-kojoampia}"      # ghcr.io/<owner>, matches release.yml's repository_owner
REGISTRY_OVERRIDE="${REGISTRY:-}"

# --- Argument parsing --------------------------------------------------------------------------

CHANNEL="local"
SKIP_BUILD=false
VERIFY_ONLY=false
ASSUME_YES=false
BOOTSTRAP=false
RECOVER=false
WITH_NGINX=false
WITH_TLS=false

while [[ $# -gt 0 ]]; do
  case "$1" in
    # Guarded: a bare trailing `--channel` would otherwise shift twice off a one-element list and
    # abort on the failed shift, swallowing the "needs a value" message below.
    --channel)     CHANNEL="${2:-}"; if [[ $# -gt 1 ]]; then shift; fi ;;
    --channel=*)   CHANNEL="${1#--channel=}" ;;
    --skip-build)  SKIP_BUILD=true ;;
    --verify-only) VERIFY_ONLY=true; SKIP_BUILD=true ;;
    --yes|-y)      ASSUME_YES=true ;;
    --bootstrap)   BOOTSTRAP=true ;;
    --recover)     RECOVER=true; SKIP_BUILD=true ;;
    --with-nginx)  WITH_NGINX=true ;;
    --with-tls)    WITH_TLS=true; WITH_NGINX=true ;;
    -h|--help)     sed -n '2,38p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
  shift
done

case "$CHANNEL" in
  local)  REGISTRY="${REGISTRY_OVERRIDE:-$LOCAL_REGISTRY}" ;;
  github)
    REGISTRY="${REGISTRY_OVERRIDE:-ghcr.io/$GHCR_OWNER}"
    # The images already exist; there is nothing here to build and a local build would produce a
    # different image under the same name. Forced rather than merely defaulted, so
    # `--channel github` cannot be combined into something that quietly rebuilds.
    SKIP_BUILD=true
    ;;
  "") echo "--channel needs a value: local or github" >&2; exit 2 ;;
  *)  echo "unknown channel '$CHANNEL' (expected: local, github)" >&2; exit 2 ;;
esac

# Domain for the nginx site and certbot, derived from PUBLIC_URL (https://host -> host).
# Only this one host is served: the apex (abofonsa.com) is deliberately not claimed, because it is
# a separate hostname that may already serve something else. See infra/prod-server/nginx-abofonsa.conf.
PUBLIC_HOST="${PUBLIC_URL#https://}"; PUBLIC_HOST="${PUBLIC_HOST#http://}"; PUBLIC_HOST="${PUBLIC_HOST%%/*}"

# Channel-dependent, and it has to be: build.sh tags with the short SHA, while release.yml tags
# with ${{ github.sha }} - the full 40-character one. Defaulting to the short SHA on the github
# channel would look up an image that was never pushed and fail with a bare manifest-unknown.
if [[ -z "${TAG:-}" ]]; then
  if [[ "$CHANNEL" == "github" ]]; then TAG="$(git rev-parse HEAD)"; else TAG="$(git rev-parse --short HEAD)"; fi
fi

# --- Output helpers ----------------------------------------------------------------------------

if [[ -t 1 ]]; then
  BOLD=$'\033[1m'; RED=$'\033[31m'; GREEN=$'\033[32m'; YELLOW=$'\033[33m'; RESET=$'\033[0m'
else
  BOLD=""; RED=""; GREEN=""; YELLOW=""; RESET=""
fi

step()  { echo ""; echo "${BOLD}==> $*${RESET}"; }
ok()    { echo "  ${GREEN}✓${RESET} $*"; }
warn()  { echo "  ${YELLOW}!${RESET} $*"; }
fail()  { echo "  ${RED}✗${RESET} $*"; }
die()   { echo ""; echo "${RED}${BOLD}Aborted:${RESET} $*" >&2; exit 1; }

confirm() {
  $ASSUME_YES && return 0
  local reply
  read -r -p "  ${BOLD}$1${RESET} [y/N] " reply
  [[ "$reply" =~ ^[Yy]$ ]] || die "declined at: $1"
}

# -n matters: without it ssh reads this script's stdin and forwards it to the remote command,
# which silently eats the answers to the confirm() prompts below. The one place that genuinely
# needs stdin - writing .env during bootstrap - calls ssh directly.
remote() { ssh -n "$SSH_HOST" "$@"; }
in_dir() { ssh -n "$SSH_HOST" "cd $REMOTE_DIR && $*"; }

# Tracks non-fatal problems so the final summary reports them together rather than burying them.
WARNINGS=()
note_warning() { WARNINGS+=("$1"); warn "$1"; }

# Rewrites a key in the server's .env, appending it if it is absent. sed alone is not enough: a
# `sed -i 's/^REGISTRY=.*/.../'` against an .env that predates the github channel matches nothing
# and exits 0, leaving compose.yml to fall back to its built-in `${REGISTRY:-docker.jojoaddison.net}`
# and pull the old registry's copy of a tag that only exists on GHCR.
# `|` is the sed delimiter because every registry value contains slashes.
set_env_key() {
  local key="$1" value="$2"
  in_dir "if grep -q '^$key=' .env; then sed -i 's|^$key=.*|$key=$value|' .env; \
          else printf '%s\n' '$key=$value' >> .env; fi"
}

# Rolling back means restoring the previous IMAGE, and the previous image may have come from the
# other channel - so the hint has to name the channel that can actually produce it. Suggesting
# `--skip-build` for a GHCR deployment would reset REGISTRY to the private registry and look for a
# full-SHA tag that was never pushed there. Reads the globals when called, after they are known.
rollback_hint() {
  case "${PREVIOUS_REGISTRY:-}" in
    ghcr.io/*) echo "TAG=${PREVIOUS_TAG:-<previous>} ./deploy.sh --channel github" ;;
    *)         echo "TAG=${PREVIOUS_TAG:-<previous>} ./deploy.sh --skip-build" ;;
  esac
}

# --- 1. Preflight ------------------------------------------------------------------------------

step "Preflight"

echo "  target:   $SSH_HOST:$REMOTE_DIR"
echo "  public:   $PUBLIC_URL"
echo "  channel:  $CHANNEL$([[ "$CHANNEL" == github ]] && echo '  (images built by GitHub Actions)' || echo '  (images built here by ./build.sh)')"
echo "  registry: $REGISTRY${REGISTRY_OVERRIDE:+  (from \$REGISTRY, overriding the channel default)}"
echo "  tag:      $TAG"
if $VERIFY_ONLY; then                    MODE_DESC="verify only"
elif [[ "$CHANNEL" == "github" ]]; then  MODE_DESC="deploy the GitHub-built image (nothing is built here)"
elif $SKIP_BUILD; then                   MODE_DESC="redeploy (no build)"
else                                     MODE_DESC="full build + deploy"
fi
echo "  mode:     $MODE_DESC"

command -v docker >/dev/null || die "docker not found on PATH"
command -v ssh    >/dev/null || die "ssh not found on PATH"

ssh -n -o BatchMode=yes -o ConnectTimeout=10 "$SSH_HOST" true 2>/dev/null \
  || die "cannot ssh to '$SSH_HOST' non-interactively. Check ~/.ssh/config and your agent."
ok "ssh to $SSH_HOST works"

# The container names above are duplicated from compose.yml, and drifted once already: compose was
# renamed and this script kept polling a container that no longer existed, so a perfectly good
# deploy sat waiting for health on a ghost. Check the two agree before doing anything.
for expected in "$API_CONTAINER" "$WEB_CONTAINER" "$MONGO_CONTAINER"; do
  grep -q "container_name: *$expected\b" infra/prod-server/compose.yml \
    || die "this script expects a container named '$expected', but infra/prod-server/compose.yml
        does not declare it. The two have drifted - reconcile them before deploying."
done
ok "container names agree with compose.yml"

CONTAINERS_EXIST=false
remote "docker inspect $API_CONTAINER >/dev/null 2>&1" && CONTAINERS_EXIST=true

if remote "test -f $REMOTE_DIR/compose.yml && test -f $REMOTE_DIR/.env"; then
  ok "remote deployment directory looks initialized"
  if $BOOTSTRAP; then
    # Re-running --bootstrap over a live install regenerates .env with new secrets. That orphans
    # nothing in Mongo (it has no password here), but it DOES invalidate every issued admin token
    # and silently reset every enquiry rate-limit bucket - a confusing state that looks like a
    # broken build. Refuse instead.
    die "$REMOTE_DIR already has compose.yml and .env - this is an existing install, not a new one.
        Drop --bootstrap to deploy to it normally. If you really want to start over, remove
        $REMOTE_DIR (and its Docker volumes) on the server first, deliberately."
  fi
elif $CONTAINERS_EXIST && $RECOVER; then
  warn "config files are missing but the stack is running - recovering them"
elif $CONTAINERS_EXIST; then
  # The dangerous case, and the reason --recover exists: the stack is running but its compose.yml
  # and .env are gone. Bootstrapping over this looks like the obvious move and is destructive:
  #
  #   - It generates a new BOOTSTRAP_ADMIN_PASSWORD, but the admin user was already seeded and the
  #     changelog runner records V008 as applied, so it will NOT be re-seeded. The new password
  #     matches nothing, and the old one is gone with the .env - CMS access is lost permanently.
  #   - It generates a new JWT_SIGNING_KEY and ENQUIRY_IP_SALT, invalidating every session and
  #     silently resetting every rate-limit bucket.
  #
  # The secrets are still recoverable, because the running containers hold them in their
  # environment. --recover reconstructs .env from there instead of inventing new values.
  die "$REMOTE_DIR has no compose.yml/.env, but $API_CONTAINER is running.

        The stack is orphaned: it is serving, but nothing on the server can manage it - no
        compose file to act on, and the secrets exist only inside the running containers.

        Do NOT bootstrap over this. Bootstrapping would generate a new BOOTSTRAP_ADMIN_PASSWORD
        that cannot match the already-seeded admin user (the migration will not re-run), and the
        real one would be gone for good.

        Run:  ./deploy.sh --recover
        which rebuilds .env from the running containers' own environment and ships the missing
        files back, changing no secret and restarting nothing."
elif $RECOVER; then
  die "--recover expects a running stack whose config files are missing, but $API_CONTAINER
        does not exist. There is nothing to recover secrets from; use --bootstrap for a fresh
        install."
else
  $BOOTSTRAP || die "$REMOTE_DIR is missing compose.yml and/or .env, so there is nothing to update.
        For a first-time install, re-run with --bootstrap (add --with-nginx --with-tls to also
        set up the host nginx site and its certificate). See
        infra/PRODUCTION_DEPLOYMENT_PLAN.md for what that provisions."
  warn "no existing deployment found - will bootstrap a new one"
fi

if ! $SKIP_BUILD; then
  # Deploying a dirty tree means the pushed image doesn't match any commit, which makes the TAG
  # meaningless for tracing a bug back to source later.
  if [[ -n "$(git status --porcelain --untracked-files=no)" ]]; then
    note_warning "working tree has uncommitted changes - image $TAG will not match commit $TAG"
    confirm "Build and push anyway?"
  else
    ok "working tree clean (image tag $TAG matches the commit)"
  fi
elif [[ "$CHANNEL" == "github" ]] && ! $VERIFY_ONLY && ! $RECOVER; then
  # A dirty tree means something different on this channel, and something quieter. Nothing is built
  # here, so there is no mismatched tag to warn about - the image for $TAG was built from the commit
  # and simply does not contain the changes sitting in front of you. Without this you can edit,
  # deploy, and watch the edit not appear, with every step reporting success.
  if [[ "$TAG" == "$(git rev-parse HEAD)" && -n "$(git status --porcelain --untracked-files=no)" ]]; then
    note_warning "working tree has uncommitted changes, and this channel deploys the image built from commit $TAG - your local edits are NOT in it"
  fi
fi

PREVIOUS_TAG=""
PREVIOUS_REGISTRY=""
if ! $BOOTSTRAP; then
  PREVIOUS_TAG="$(in_dir "grep -E '^TAG=' .env | cut -d= -f2" || true)"
  PREVIOUS_REGISTRY="$(in_dir "grep -E '^REGISTRY=' .env | cut -d= -f2" || true)"
  [[ -n "$PREVIOUS_TAG" ]] && echo "  currently deployed tag: ${BOLD}${PREVIOUS_TAG}${RESET}"
  # Switching channels is legitimate and is exactly what this flag is for, but it is also the kind
  # of thing worth seeing stated rather than inferring from a pull that suddenly takes five minutes.
  if [[ -n "$PREVIOUS_REGISTRY" && "$PREVIOUS_REGISTRY" != "$REGISTRY" ]] && ! $VERIFY_ONLY && ! $RECOVER; then
    echo "  ${BOLD}registry change:${RESET} $PREVIOUS_REGISTRY -> $REGISTRY"
  fi
fi

# --verify-only inspects whatever is already live, so the local checkout's commit is irrelevant -
# without this the image-tag check below would "fail" simply because you have newer local commits.
# The registry follows for the same reason: what is live may well have come from the other channel.
if $VERIFY_ONLY && [[ -n "$PREVIOUS_TAG" ]]; then
  TAG="$PREVIOUS_TAG"
  REGISTRY="${PREVIOUS_REGISTRY:-$REGISTRY}"
fi

# --- 1a. github channel: prove the images exist before touching anything -----------------------
# Deliberately the last thing in preflight, and deliberately not in the build step further down:
# every message below promises the server is untouched, and that promise has to still be true when
# it prints. Bootstrap creates directories, a network and an .env before the build step is reached,
# so a probe placed there could only apologise for work already done.

if [[ "$CHANNEL" == "github" ]] && ! $VERIFY_ONLY && ! $RECOVER; then
  step "Checking the GitHub-built images for $TAG are pullable from $SSH_HOST"
  echo "  Nothing is built on this channel. .github/workflows/release.yml built and pushed these"
  echo "  when the commit landed on main; this only confirms they are there and reachable."
  echo ""
  echo "  The probe runs ON THE SERVER, not here, because the server is what pulls: a local"
  echo "  ~/.docker/config.json that happens to hold a GHCR token proves nothing about whether"
  echo "  the deploy will work. Checking it here would turn a permissions problem into a failed"
  echo "  'docker compose pull' after .env has already been rewritten to a tag that cannot start."

  GHCR_MISSING=()
  GHCR_UNAUTHORIZED=false
  GHCR_PROBE_UNSUPPORTED=false
  for image in "$REGISTRY/abofonsa-api:$TAG" "$REGISTRY/abofonsa-web:$TAG"; do
    # stderr only: the manifest JSON itself is noise, the error text is the diagnosis.
    if probe_err="$(remote "docker manifest inspect '$image' 2>&1 >/dev/null")"; then
      ok "$image"
    else
      # GHCR answers an unauthenticated request for a private package with 'denied'/'unauthorized'
      # rather than 404 - deliberately, so the registry does not leak which packages exist. The two
      # cases need completely different fixes, so they are told apart rather than merged into
      # "could not find the image".
      case "$probe_err" in
        *nauthorized*|*denied*|*"requested access"*) GHCR_UNAUTHORIZED=true ;;
        # `docker manifest` needed DOCKER_CLI_EXPERIMENTAL=enabled before CLI 20.10. That says
        # nothing about the image, and blocking a perfectly good deploy on it - while reporting it
        # as a missing tag - would be worse than not checking at all.
        *xperimental*) GHCR_PROBE_UNSUPPORTED=true ;;
      esac
      GHCR_MISSING+=("$image")
      fail "$image -> ${probe_err:-not reachable}"
    fi
  done

  if $GHCR_PROBE_UNSUPPORTED; then
    note_warning "$SSH_HOST's docker CLI does not support 'docker manifest inspect' - could not pre-check the images"
    echo "      The deploy continues unchecked; if the images are absent or the credential is"
    echo "      missing, it will fail at 'docker compose pull' in a few steps' time instead."
    GHCR_MISSING=()
  fi

  if (( ${#GHCR_MISSING[@]} > 0 )); then
    if $GHCR_UNAUTHORIZED; then
      if remote "grep -q ghcr.io ~/.docker/config.json 2>/dev/null"; then
        die "$SSH_HOST has a stored ghcr.io credential but GHCR still refused the pull.

        The token is most likely expired, or lacks the read:packages scope. Refresh it on the
        server with a token that has read:packages:

          ssh $SSH_HOST 'echo <TOKEN> | docker login ghcr.io -u $GHCR_OWNER --password-stdin'

        Nothing has been changed on the server; the running deployment is untouched."
      fi
      die "these packages are private and $SSH_HOST has no ghcr.io credential.

        Either make the packages public (GitHub -> Packages -> abofonsa-api / abofonsa-web ->
        Package settings -> Change visibility), which needs no credential on the server at all,
        or store a read-only token there once:

          ssh $SSH_HOST 'echo <TOKEN> | docker login ghcr.io -u $GHCR_OWNER --password-stdin'

        The token needs the read:packages scope and nothing else - it is only ever used to pull.
        Nothing has been changed on the server; the running deployment is untouched."
    fi
    # owner/repo out of the git remote, handling both the SSH and HTTPS forms, so the link is
    # clickable rather than a placeholder - and stays right if the repo moves or is forked.
    REPO_SLUG="$(git remote get-url origin 2>/dev/null || true)"
    REPO_SLUG="${REPO_SLUG%.git}"
    REPO_SLUG="${REPO_SLUG#*github.com}"
    REPO_SLUG="${REPO_SLUG#[:/]}"
    case "$REPO_SLUG" in
      */*) ACTIONS_URL="https://github.com/$REPO_SLUG/actions/workflows/release.yml" ;;
      *)   ACTIONS_URL="https://github.com/$GHCR_OWNER/<repo>/actions/workflows/release.yml" ;;
    esac
    die "GHCR has no image tagged $TAG.

        This channel deploys what GitHub Actions built, so a missing tag means the Release
        workflow has not produced this commit: it may not be merged to main yet, or the run
        failed, or you are deploying a commit that only exists locally.

          - check the run:  $ACTIONS_URL
          - to deploy a different, already-built commit:  TAG=<full-sha> ./deploy.sh --channel github
          - to deploy this working tree instead:          ./deploy.sh   (the local channel)

        Note the tag is the FULL 40-character SHA on this channel, not the short one build.sh uses.

        Nothing has been changed on the server; the running deployment is untouched."
  fi
  # Not printed when the probe could not run: an unchecked deploy must not report a clean check.
  $GHCR_PROBE_UNSUPPORTED || ok "both images exist on GHCR and $SSH_HOST can pull them"
fi

# --- 1b. Recover an orphaned deployment --------------------------------------------------------
# Puts the missing files back without touching the running containers. The secrets come out of the
# API container's own environment, so they stay identical to what the database was seeded with -
# which is the whole point, since a regenerated BOOTSTRAP_ADMIN_PASSWORD would match nothing.

if $RECOVER; then
  step "Recovering $REMOTE_DIR from the running stack"
  echo "  Rebuilds compose.yml, start, infra.sh, backup.sh and .env."
  echo "  Secrets are read from $API_CONTAINER's environment on the server and never leave it."
  echo "  Nothing is restarted and no secret changes."
  confirm "Proceed with recovery?"

  remote "mkdir -p $REMOTE_DIR/backups"
  scp -q infra/prod-server/compose.yml infra/prod-server/start \
         infra/prod-server/infra.sh infra/prod-server/backup.sh "$SSH_HOST:$REMOTE_DIR/"
  remote "chmod +x $REMOTE_DIR/start $REMOTE_DIR/infra.sh $REMOTE_DIR/backup.sh"
  ok "restored compose.yml, start, infra.sh, backup.sh"

  # Entirely server-side: docker inspect feeds the values straight into .env, so no secret is
  # printed here or crosses the wire. The running image reference is recovered the same way, so the
  # rebuilt .env pins exactly what is live rather than guessing `latest` - or guessing a registry.
  # REGISTRY below is only a fallback for the impossible case where the image reference has no
  # registry component; the live reference is what decides, because with two channels the flag this
  # invocation happened to be given is no longer evidence of where the running images came from.
  # shellcheck disable=SC2087  # the inner heredoc must expand remotely
  ssh "$SSH_HOST" \
    "ENV_PATH=$REMOTE_DIR/.env API_CONTAINER='$API_CONTAINER' WEB_CONTAINER='$WEB_CONTAINER' \
     REGISTRY='$REGISTRY' FRONTEND_PORT='$FRONTEND_PORT' STAMP='$(date -u +%Y-%m-%dT%H:%M:%SZ)' \
     bash -s" <<'REMOTE_SCRIPT'
set -euo pipefail
umask 077

envof() { docker inspect "$1" --format '{{range .Config.Env}}{{println .}}{{end}}' | grep "^$2=" | cut -d= -f2-; }

JWT="$(envof "$API_CONTAINER" JWT_SIGNING_KEY)"
BOOTSTRAP_PW="$(envof "$API_CONTAINER" BOOTSTRAP_ADMIN_PASSWORD)"
SALT="$(envof "$API_CONTAINER" ENQUIRY_IP_SALT)"
ALLOWED="$(envof "$WEB_CONTAINER" ALLOWED_HOSTS)"
INDEXABLE="$(envof "$WEB_CONTAINER" SITE_INDEXABLE)"
# Split from the whole reference (registry/namespace/name:tag) rather than assumed, so a stack
# running GHCR images is recovered as a GHCR deployment and the next `docker compose pull` looks
# where the images actually are.
LIVE_IMAGE="$(docker inspect "$API_CONTAINER" --format '{{.Config.Image}}')"
LIVE_TAG="${LIVE_IMAGE##*:}"
case "$LIVE_IMAGE" in
  # Everything before the last slash: 'ghcr.io/owner' or 'docker.example.net' alike.
  */*) LIVE_REGISTRY="${LIVE_IMAGE%/*}" ;;
  # No slash means no registry component to recover; fall back to the invoking channel's value.
  # Testing the registry rather than the whole reference here would misread a bare 'abofonsa-api:tag'
  # as the registry 'abofonsa-api:tag' and write that into .env.
  *)   LIVE_REGISTRY="$REGISTRY" ;;
esac

for pair in "JWT_SIGNING_KEY:$JWT" "BOOTSTRAP_ADMIN_PASSWORD:$BOOTSTRAP_PW" "ENQUIRY_IP_SALT:$SALT"; do
  [ -n "${pair#*:}" ] || { echo "could not recover ${pair%%:*} from the container" >&2; exit 1; }
done

cat > "$ENV_PATH" <<ENVEOF
# Rebuilt by deploy.sh --recover on $STAMP from the running containers' environment.
# Every secret below is the value the live stack is already using - not a regenerated one.
REGISTRY=$LIVE_REGISTRY
TAG=$LIVE_TAG
FRONTEND_PORT=$FRONTEND_PORT

JWT_SIGNING_KEY=$JWT
BOOTSTRAP_ADMIN_PASSWORD=$BOOTSTRAP_PW
ENQUIRY_IP_SALT=$SALT

ALLOWED_HOSTS=${ALLOWED:-web.abofonsa.com}
SITE_INDEXABLE=${INDEXABLE:-false}
ENVEOF
chmod 600 "$ENV_PATH"
echo "recovered REGISTRY=$LIVE_REGISTRY TAG=$LIVE_TAG"
REMOTE_SCRIPT
  ok "rebuilt .env (mode 600) from the live containers - no secret changed"

  in_dir "docker compose --env-file .env -f compose.yml config >/dev/null" \
    && ok "compose.yml + .env resolve cleanly" \
    || die "the recovered files do not resolve - inspect $REMOTE_DIR/.env by hand"

  # JWT_SIGNING_KEY and ENQUIRY_IP_SALT are recovered soundly, because the live container is
  # *using* them right now - its copy is the truth by definition.
  #
  # BOOTSTRAP_ADMIN_PASSWORD is different in kind, and assuming otherwise is a trap this script
  # walked into once. It matters only at seed time: V008 hashes it into the admin record on first
  # boot and is then recorded in `schemaMigrations`, never to run again. A container started later
  # can therefore carry a perfectly valid-looking value that has nothing to do with the stored
  # hash - which is exactly what happens when a failed deploy recreates the stack with a freshly
  # generated .env. Recovering that value silently would hand over a password that cannot work.
  #
  # So it is tested, on the server, against the running API. Addressed by the compose service
  # alias rather than the container name: `hc_abofonsa_api` contains underscores, which are illegal
  # in a hostname, and Tomcat rejects the request with a bare 400 before Spring ever sees it.
  step "Checking the recovered admin password actually works"
  RECOVERED_LOGIN_CODE="$(remote "cd $REMOTE_DIR && python3 -c \"
import json,re,pathlib
env=dict(re.match(r'^([A-Z_]+)=(.*)\$', l).groups() for l in pathlib.Path('.env').read_text().splitlines() if re.match(r'^[A-Z_]+=', l))
pathlib.Path('/tmp/.abofonsa-login-probe.json').write_text(json.dumps({'username':'admin','password':env['BOOTSTRAP_ADMIN_PASSWORD']}))
\" && docker run --rm --network $APP_NETWORK -v /tmp/.abofonsa-login-probe.json:/p.json:ro curlimages/curl:latest \
       -s -o /dev/null -w '%{http_code}' -X POST http://api:8080/api/v1/admin/auth/login \
       -H 'Content-Type: application/json' --data-binary @/p.json; rm -f /tmp/.abofonsa-login-probe.json" || echo "000")"

  case "$RECOVERED_LOGIN_CODE" in
    200) ok "BOOTSTRAP_ADMIN_PASSWORD authenticates - CMS access is intact" ;;
    401)
      note_warning "the recovered BOOTSTRAP_ADMIN_PASSWORD does NOT authenticate"
      echo "      This value is not the one the admin account was seeded with, so nobody can sign"
      echo "      in to the CMS. It is not recoverable: only its BCrypt hash was ever stored, and"
      echo "      V008_seed_admin_user is already recorded in schemaMigrations, so it will not"
      echo "      re-run on its own."
      echo ""
      echo "      To reset the account to the password now in .env - this DELETES the unusable"
      echo "      admin user and lets the seeder recreate it, so run it deliberately:"
      echo ""
      echo "        ssh $SSH_HOST \"docker exec $MONGO_CONTAINER mongosh abofonsa --quiet --eval '"
      echo "          db.adminUsers.deleteMany({username: \\\"admin\\\"});"
      echo "          db.schemaMigrations.deleteOne({_id: \\\"V008_seed_admin_user\\\"});'\""
      echo "        ssh $SSH_HOST 'cd $REMOTE_DIR && docker compose --env-file .env -f compose.yml restart api'"
      echo ""
      echo "      The recreated account keeps mustChangePassword=true, so the first login must"
      echo "      still rotate it. Any other admin users are untouched."
      ;;
    *) note_warning "could not verify BOOTSTRAP_ADMIN_PASSWORD (login probe returned $RECOVERED_LOGIN_CODE)" ;;
  esac

  PREVIOUS_TAG="$(in_dir "grep -E '^TAG=' .env | cut -d= -f2" || true)"
  PREVIOUS_REGISTRY="$(in_dir "grep -E '^REGISTRY=' .env | cut -d= -f2" || true)"
  echo "  recovered image: ${BOLD}${PREVIOUS_REGISTRY}/abofonsa-api:${PREVIOUS_TAG}${RESET}"
  TAG="$PREVIOUS_TAG"
  REGISTRY="${PREVIOUS_REGISTRY:-$REGISTRY}"
fi

# --- 1c. Bootstrap: provision a brand-new deployment -------------------------------------------
# The code form of infra/PRODUCTION_DEPLOYMENT_PLAN.md steps 1-3. nginx and TLS (steps 4) come
# later, after the stack is proven healthy on the server itself.

if $BOOTSTRAP; then
  step "Bootstrapping a new deployment at $SSH_HOST:$REMOTE_DIR"
  echo "  This will create:"
  echo "    - $REMOTE_DIR/ (plus backups/)"
  echo "    - the '$APP_NETWORK' Docker network, if absent"
  echo "    - compose.yml, start, infra.sh, backup.sh from infra/prod-server/"
  echo "    - .env with freshly generated JWT_SIGNING_KEY, BOOTSTRAP_ADMIN_PASSWORD, ENQUIRY_IP_SALT,"
  echo "      pinned to REGISTRY=$REGISTRY (the '$CHANNEL' channel) and TAG=$TAG"
  $WITH_NGINX && echo "    - /etc/nginx/sites-available/$NGINX_CONF for $PUBLIC_HOST (after the stack is healthy)"
  $WITH_TLS   && echo "    - a Let's Encrypt certificate for $PUBLIC_HOST (after nginx)"
  echo "  It will NOT touch any other app on this server."
  confirm "Proceed with bootstrap?"

  remote "mkdir -p $REMOTE_DIR/backups"
  ok "created $REMOTE_DIR/ and backups/"

  # compose.yml declares both networks `external: true`, so compose will not create them itself -
  # it just fails with a bare "network not found" if either is missing.
  if remote "docker network inspect $APP_NETWORK >/dev/null 2>&1"; then
    ok "docker network '$APP_NETWORK' already exists"
  else
    remote "docker network create $APP_NETWORK >/dev/null"
    ok "created docker network '$APP_NETWORK'"
  fi

  # 'monitoring' belongs to the server's shared observability stack (~/webroot/00-admin/monitoring),
  # not to this app. Creating our own empty one here would let compose start while the OTel agent
  # quietly fails to reach a collector and Prometheus never finds the scrape target.
  if remote "docker network inspect monitoring >/dev/null 2>&1"; then
    ok "docker network 'monitoring' exists (OTel export and scraping will work)"
  else
    note_warning "docker network 'monitoring' does not exist on this server"
    echo "      compose.yml attaches the api to it. Either start the shared monitoring stack"
    echo "      first, or drop the 'monitoring' network from compose.yml for this host."
    echo "      Continuing will fail at 'docker compose up'."
    confirm "Continue anyway?"
  fi

  scp -q infra/prod-server/compose.yml infra/prod-server/start \
         infra/prod-server/infra.sh infra/prod-server/backup.sh "$SSH_HOST:$REMOTE_DIR/"
  remote "chmod +x $REMOTE_DIR/start $REMOTE_DIR/infra.sh $REMOTE_DIR/backup.sh"
  ok "shipped compose.yml, start, infra.sh, backup.sh"

  # The secrets are generated ON THE SERVER, never here. The outer heredoc delimiter is quoted
  # ('REMOTE_SCRIPT') so nothing in it expands locally — the whole block is shipped verbatim over
  # ssh's stdin and run there, so `openssl rand` executes remotely and no secret ever exists on the
  # deploying machine, in its shell history, or on the wire. Only the non-secret values are
  # interpolated locally, as environment assignments; those are visible in the server's process
  # list, which is exactly why no secret is passed that way.
  #
  # JWT_SIGNING_KEY: HS512 needs >= 64 bytes of key material, hence rand 64 (not 48).
  # ENQUIRY_IP_SALT: salts the hash of visitor IPs so stored hashes cannot be reversed.
  # BOOTSTRAP_ADMIN_PASSWORD: usable exactly once - the account is created with
  #   mustChangePassword=true and every other endpoint refuses that token until it is rotated.
  # shellcheck disable=SC2087  # the inner heredoc is meant to expand remotely; that is the point
  ssh "$SSH_HOST" \
    "ENV_PATH=$REMOTE_DIR/.env \
     REGISTRY='$REGISTRY' TAG='$TAG' FRONTEND_PORT='$FRONTEND_PORT' \
     ALLOWED='$PUBLIC_HOST' STAMP='$(date -u +%Y-%m-%dT%H:%M:%SZ)' \
     bash -s" <<'REMOTE_SCRIPT'
set -euo pipefail
umask 077
cat > "$ENV_PATH" <<ENVEOF
# Generated by deploy.sh --bootstrap on $STAMP.
# The secrets below were generated on this server with 'openssl rand' and have never left it.
# Keep this file mode 600.
REGISTRY=$REGISTRY
TAG=$TAG
FRONTEND_PORT=$FRONTEND_PORT

# Rotating this invalidates every issued access and refresh token, logging all staff out.
# That is the correct response to a suspected leak.
JWT_SIGNING_KEY=$(openssl rand -base64 64 | tr -d '\n')

# Single-use: rotate at first CMS login (the app forces it). See GO-LIVE-CHECKLIST.md.
BOOTSTRAP_ADMIN_PASSWORD=$(openssl rand -base64 24)

# Changing this resets every enquiry rate-limit counter.
ENQUIRY_IP_SALT=$(openssl rand -base64 32)

# Angular's SSR engine rejects any Host not listed here. Must match what nginx forwards.
ALLOWED_HOSTS=$ALLOWED
ENVEOF
chmod 600 "$ENV_PATH"
REMOTE_SCRIPT
  ok "wrote .env (mode 600); secrets generated on the server and never transmitted"

  PREVIOUS_TAG=""        # nothing was deployed before; keeps the summary's rollback hint honest
  PREVIOUS_REGISTRY=""
fi

