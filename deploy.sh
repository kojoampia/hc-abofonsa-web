# --- 4. Check the server's .env for required keys ----------------------------------------------
# Reads key names only - values stay on the server and are never printed or copied here.

if ! $VERIFY_ONLY && ! $RECOVER; then
  step "Checking the server's .env"

  REMOTE_ENV_KEYS="$(in_dir "grep -oE '^[A-Z_]+' .env" | sort)"

  # compose.yml marks these `:?` - a missing one aborts `docker compose up` with an error that
  # doesn't obviously point at .env, so catch it here where the message can be specific.
  for key in JWT_SIGNING_KEY BOOTSTRAP_ADMIN_PASSWORD ENQUIRY_IP_SALT; do
    grep -qx "$key" <<<"$REMOTE_ENV_KEYS" || die "$REMOTE_DIR/.env is missing required key $key
        (compose.yml declares it \`:?\`, so the stack will refuse to start)."
  done
  ok "all required keys present"

  # HS512 refuses a key shorter than 64 bytes at startup, and the failure surfaces as a bean
  # creation error rather than anything mentioning .env.
  #
  # Strips the key name with sub() rather than splitting on '=': base64 values end in '=' padding,
  # so -F= would measure only up to the first one and report a legitimate 64-character key as 63.
  if ! in_dir "awk '/^JWT_SIGNING_KEY=/{sub(/^JWT_SIGNING_KEY=/,\"\"); if (length(\$0) >= 64) f=1} END{exit !f}' .env"; then
    die "JWT_SIGNING_KEY in $REMOTE_DIR/.env is shorter than 64 characters.
        HS512 needs at least 64 bytes of key material: openssl rand -base64 64"
  fi
  ok "JWT_SIGNING_KEY is long enough for HS512"

  # ALLOWED_HOSTS is not `:?` (it has a default), but a mismatch makes every page 400 with
  # "Header host ... is not allowed" - a failure that looks like a broken build.
  if in_dir "grep -qE '^ALLOWED_HOSTS=.+' .env"; then
    if ! in_dir "grep -E '^ALLOWED_HOSTS=' .env | grep -q '$PUBLIC_HOST'"; then
      note_warning "ALLOWED_HOSTS on the server does not mention $PUBLIC_HOST - SSR will reject every request with 400"
    else
      ok "ALLOWED_HOSTS includes $PUBLIC_HOST"
    fi
  else
    note_warning "ALLOWED_HOSTS not set on the server - falling back to compose.yml's default"
  fi
fi

