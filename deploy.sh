step "Internal checks (on the server, bypassing nginx and TLS)"
# Split from the public checks deliberately: if these pass but the public ones fail, the problem is
# nginx/TLS/DNS, not the app.
#
# The Host header is not optional here. Angular's SSR engine rejects any Host outside ALLOWED_HOSTS
# (its SSRF defence), so a bare `curl 127.0.0.1:8082/` sends `Host: 127.0.0.1:8082` and gets a flat
# 400 from a perfectly healthy container. nginx sets `Host: $http_host` when it proxies, so these
# checks send the same thing — otherwise they test the allowlist rather than the application, and
# report a broken deployment when nothing is wrong.
check_internal() {
  local path="$1" desc="$2"
  local code
  code="$(remote "curl -s -o /dev/null -w '%{http_code}' --max-time 20 -H 'Host: $PUBLIC_HOST' http://127.0.0.1:$FRONTEND_PORT$path" || echo "000")"
  if [[ "$code" == "200" ]]; then ok "$desc -> 200"; else fail "$desc -> $code"; return 1; fi
}
check_internal "/"                              "home page (SSR)"
check_internal "/api/v1/health"                 "API health (proxied through the web container)"
check_internal "/api/v1/content/site?locale=en" "published content payload"

# --- 8b. Bootstrap: host nginx site and TLS ----------------------------------------------------
# Runbook step 4, deliberately after the internal checks: pointing nginx at a stack that isn't
# serving yet just produces a 502 and a confusing certbot failure.

if $BOOTSTRAP && $WITH_NGINX; then
  step "Installing the host nginx site for $PUBLIC_HOST"

  if remote "test -e /etc/nginx/sites-available/$NGINX_CONF"; then
    ok "$NGINX_CONF already exists on the server - leaving it alone"
    warn "if it needs updating, edit infra/prod-server/$NGINX_CONF and copy it up by hand"
  else
    echo "  Writes /etc/nginx/sites-available/$NGINX_CONF (HTTP-only bootstrap version),"
    echo "  symlinks it into sites-enabled, tests the config, and reloads nginx."
    echo "  Other apps' sites on this host are untouched; a failed 'nginx -t' aborts before reload."
    confirm "Install the nginx site for $PUBLIC_HOST?"

    scp -q "infra/prod-server/$NGINX_CONF" "$SSH_HOST:/tmp/$NGINX_CONF"
    remote "sudo mv /tmp/$NGINX_CONF /etc/nginx/sites-available/$NGINX_CONF \
            && sudo ln -sf /etc/nginx/sites-available/$NGINX_CONF /etc/nginx/sites-enabled/$NGINX_CONF"
    ok "site config installed and enabled"

    # nginx -t before reload: a broken config would otherwise take down every site on this host,
    # not just this one.
    if remote "sudo nginx -t" 2>&1 | sed 's/^/    /'; then
      remote "sudo systemctl reload nginx"
      ok "nginx config valid, reloaded"
    else
      remote "sudo rm -f /etc/nginx/sites-enabled/$NGINX_CONF"
      die "nginx -t failed; removed the symlink and did NOT reload. Other sites are unaffected."
    fi
  fi

  if $WITH_TLS; then
    step "Obtaining a TLS certificate for $PUBLIC_HOST"

    if remote "test -d /etc/letsencrypt/live/$PUBLIC_HOST"; then
      ok "certificate for $PUBLIC_HOST already exists - skipping certbot"
    else
      echo "  Runs: certbot --nginx -d $PUBLIC_HOST"
      echo "  This rewrites the site config in place with an SSL block + HTTP->HTTPS redirect."
      echo ""
      echo "  ${BOLD}Before you say yes:${RESET}"
      echo "    - $PUBLIC_HOST must already resolve to this server, or the challenge fails."
      echo "    - Let's Encrypt rate-limits duplicate certs (5/week per domain), and issuance"
      echo "      publishes the hostname to public Certificate Transparency logs. A wrong answer"
      echo "      here is not freely retryable and not quietly undoable."
      # Deliberately prompts even under --yes: this is an outward-facing, rate-limited, effectively
      # irreversible action against a real certificate authority and a real public log.
      read -r -p "  ${BOLD}Run certbot for $PUBLIC_HOST now?${RESET} [y/N] " reply
      if [[ "$reply" =~ ^[Yy]$ ]]; then
        remote "sudo certbot --nginx -d $PUBLIC_HOST --non-interactive --agree-tos --register-unsafely-without-email --redirect" \
          && ok "certificate issued and nginx reconfigured for HTTPS" \
          || die "certbot failed. The HTTP-only site is still serving; fix DNS and re-run certbot by hand."
      else
        note_warning "skipped certbot - $PUBLIC_URL will not work until a certificate exists"
      fi
    fi
  fi
fi

# --- 9. Public verification --------------------------------------------------------------------

if $BOOTSTRAP && ! remote "test -d /etc/letsencrypt/live/$PUBLIC_HOST" 2>/dev/null; then
  step "Public checks - skipped"
  note_warning "no TLS certificate on the server yet, so $PUBLIC_URL cannot be checked"
  echo "      Finish by pointing DNS at this server and re-running with --with-nginx --with-tls,"
  echo "      or by running certbot on the server yourself. Then: ./deploy.sh --verify-only"
  SKIP_PUBLIC=true
else
  SKIP_PUBLIC=false
fi

check_public() {
  local path="$1" desc="$2" expect="${3:-200}"
  local code
  code="$(curl -s -o /dev/null -w '%{http_code}' --max-time 25 "$PUBLIC_URL$path" || echo "000")"
  if [[ "$code" == "$expect" ]]; then ok "$desc -> $code"; else fail "$desc -> $code (expected $expect)"; return 1; fi
}

PUBLIC_OK=true
if ! $SKIP_PUBLIC; then
  step "Public checks ($PUBLIC_URL)"

  check_public "/"                              "home page"          || PUBLIC_OK=false
  check_public "/api/v1/health"                 "GET /api/v1/health" || PUBLIC_OK=false
  check_public "/api/v1/content/site?locale=en" "content payload"    || PUBLIC_OK=false

  # Each locale is an independently routed, server-rendered page (spec §5.4). A wrong `lang` means
  # SSR silently fell back to English, which no status code would reveal.
  #
  # The body is captured first rather than piped into grep. Under `set -o pipefail`, `curl | grep -q`
  # is actively wrong: grep exits the instant it matches, curl is left writing into a closed pipe and
  # fails with exit 23, and pipefail reports the *successful* match as a failed pipeline. It only
  # shows up on responses big enough that curl is still writing — which is why the tiny header checks
  # below always passed while this 240 kB page always "failed".
  for locale in en es fr de; do
    path=$([[ "$locale" == "en" ]] && echo "/" || echo "/$locale")
    page_html="$(curl -s --max-time 25 "$PUBLIC_URL$path" || true)"
    if grep -q "<html lang=\"$locale\"" <<<"$page_html"; then
      ok "$path renders lang=\"$locale\""
    else
      fail "$path did not render lang=\"$locale\" - SSR locale resolution is broken"
      PUBLIC_OK=false
    fi
  done

  # Publishing must be visible immediately, so the HTML must never be served stale from a cache.
  CACHE_HEADER="$(grep -i '^cache-control:' <<<"$(curl -sI --max-time 20 "$PUBLIC_URL/" || true)" | tr -d '\r' || true)"
  if grep -qi 'no-cache' <<<"$CACHE_HEADER"; then
    ok "HTML revalidates (${CACHE_HEADER:-none})"
  else
    note_warning "home page Cache-Control is '${CACHE_HEADER:-<absent>}', expected no-cache - published edits may appear stale"
  fi

  # Every response should carry a correlation id; support quotes it when reporting a problem.
  if grep -qi '^x-request-id:' <<<"$(curl -sI --max-time 20 "$PUBLIC_URL/api/v1/health" || true)"; then
    ok "responses carry X-Request-Id"
  else
    note_warning "no X-Request-Id header - correlation ids are not reaching clients"
  fi

  # Indexability is reported, never asserted: both answers are legitimate, and which one is correct
  # depends on whether this deployment is the announced site or a review of it. Getting it wrong is
  # silent and slow to undo in one direction, so it is stated plainly on every deploy.
  ROBOTS_TXT="$(curl -s --max-time 20 "$PUBLIC_URL/robots.txt" || true)"
  ROBOTS_META="$(grep -o '<meta name="robots"[^>]*>' <<<"$(curl -s --max-time 25 "$PUBLIC_URL/" || true)" | head -1 || true)"
  if grep -q 'Disallow: /$' <<<"$ROBOTS_TXT"; then
    ok "search engines are excluded (robots.txt disallows all)"
    grep -q 'noindex' <<<"$ROBOTS_META" \
      || note_warning "robots.txt disallows all but the page meta says '${ROBOTS_META:-<absent>}' - these disagree"
    echo "      To make this deployment indexable: set SITE_INDEXABLE=true in $REMOTE_DIR/.env and redeploy."
  else
    ok "search engines are allowed (robots.txt: ${ROBOTS_TXT//$'\n'/ })"
    grep -q 'noindex' <<<"$ROBOTS_META" \
      && note_warning "robots.txt allows crawling but the page still says noindex - these disagree"
    warn "this deployment is indexable - correct only if $PUBLIC_HOST is the announced public site"
  fi

  # The CMS must never be indexable, and must not be server-rendered into a login redirect.
  check_public "/admin/login" "CMS login page" || note_warning "CMS login page not reachable"

  # Certbot renews on a cron, so this is early warning, not a deploy gate.
  CERT_END="$(echo | openssl s_client -connect "$PUBLIC_HOST:443" -servername "$PUBLIC_HOST" 2>/dev/null \
    | openssl x509 -noout -enddate 2>/dev/null | cut -d= -f2 || true)"
  if [[ -n "$CERT_END" ]]; then
    CERT_DAYS=$(( ( $(date -d "$CERT_END" +%s) - $(date +%s) ) / 86400 ))
    if (( CERT_DAYS < 14 )); then
      note_warning "TLS certificate expires in $CERT_DAYS days ($CERT_END) - check certbot's renewal timer"
    else
      ok "TLS certificate valid for $CERT_DAYS more days"
    fi
  fi
fi

$PUBLIC_OK || die "public verification failed - the app is not correctly serving at $PUBLIC_URL"

